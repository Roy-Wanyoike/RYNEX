/* =====================================================================
   extensions/fleet.sql — RYNEX Fleet module (multi-vehicle management)
   ---------------------------------------------------------------------
   Spec: Fleet Platform §51 (f2) — "Fleets + vehicle assignment".
   Shipper: src/Modules/Fleet/ (mounted at /api/v1/fleet via
            src/Router/modules.ts).

   Objects created here:
     TABLE fleets
       fleetId     VARCHAR(50) PK   (uuid, generated by the API)
       ownerUserId VARCHAR(50) NOT NULL FK -> users(userId)  [CASCADE]
       name        VARCHAR(100) NOT NULL
       createdAt   DATETIME2    DEFAULT SYSUTCDATETIME()

     TABLE fleetVehicles
       id         VARCHAR(50) PK   (server-generated NEWID())
       fleetId    VARCHAR(50) FK -> fleets(fleetId) ON DELETE CASCADE
       carId      VARCHAR(50) FK -> Cars(carId)     ON DELETE CASCADE
       assignedAt DATETIME2   DEFAULT SYSUTCDATETIME()
       UNIQUE (fleetId, carId)  <- duplicate assignment is impossible;
                                   spAssignVehicleToFleet converts the
                                   violation into THROW 50802.

     PROCEDURES (all CREATE OR ALTER, idempotent, SET NOCOUNT ON):
       spCreateFleet             (@FleetId, @OwnerUserId, @Name)
                                 -> inserts and returns the fleet row.
       SpGetFleetsByUser         (@OwnerUserId)
                                 -> the user's fleets + vehicleCount
                                    subquery, newest first.
       spGetFleet                (@FleetId)
                                 -> single fleet row INCLUDING
                                    ownerUserId — the controller uses
                                    this for the ownership check.
       spGetFleetVehicles        (@FleetId)
                                 -> fleet rows JOIN Cars: carId, model,
                                    brand, prices, pictureUrl.
       spAssignVehicleToFleet    (@FleetId, @CarId)
                                 -> car must exist (THROW 50801),
                                    fleet must exist (THROW 50803);
                                    duplicate assignment via the UNIQUE
                                    constraint -> THROW 50802.
       spRemoveVehicleFromFleet  (@FleetId, @CarId)
                                 -> idempotent delete; OUTPUTs the
                                    removed assignment row (empty
                                    recordset when nothing matched).
       spGetAllFleets            ()
                                 -> admin listing: every fleet JOIN
                                    users (userName) + vehicleCount.

   Error contract (numbers surface as node-mssql err.number; the fleet
   controller maps 50801/50803 -> 404, 50802 -> 409):
     50800  FleetId, OwnerUserId and Name are required
     50801  Car not found or unavailable
     50802  Vehicle already in fleet
     50803  Fleet not found

   OWNERSHIP MODEL (enforced in the API, data provided by spGetFleet):
     A fleet is private to its owner; admins bypass the check. The SPs
     deliberately take no user parameter — authorization lives in the
     controller so the same SP serves owner and admin paths.

   Idempotency:
     Tables are created only when missing (IF OBJECT_ID guards); all
     procedures use CREATE OR ALTER. No test EXECUTE statements — safe
     to re-run at any time.
   ---------------------------------------------------------------------
   Dependency:
     REQUIRES dbo.users and dbo.Cars from database/schema_tables.sql
     (that file always runs first via database/master.sql).
   ===================================================================== */

